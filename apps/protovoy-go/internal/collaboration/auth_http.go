//go:build !js

package collaboration

import (
	"crypto/sha256"
	"crypto/subtle"
	"encoding/json"
	"errors"
	"io"
	"net/http"
	"strings"
)

func (store *AccessStore) RegisterAuthRoutes(mux *http.ServeMux, bootstrapToken string) {
	bootstrapHash := sha256.Sum256([]byte(bootstrapToken))
	route := func(pattern string, handle http.HandlerFunc) {
		mux.HandleFunc(pattern, func(w http.ResponseWriter, r *http.Request) {
			w.Header().Set("Cache-Control", "no-store")
			handle(w, r)
		})
	}
	authenticate := func(w http.ResponseWriter, r *http.Request, bootstrap bool) {
		var input struct {
			Email            string `json:"email"`
			Password         string `json:"password"`
			DisplayName      string `json:"displayName"`
			OrganizationName string `json:"organizationName"`
		}
		data, err := io.ReadAll(http.MaxBytesReader(w, r.Body, 8<<10))
		var limit *http.MaxBytesError
		switch {
		case errors.As(err, &limit):
			http.Error(w, "authentication request is too large", http.StatusRequestEntityTooLarge)
			return
		case err != nil || json.Unmarshal(data, &input) != nil:
			http.Error(w, "invalid authentication request", http.StatusBadRequest)
			return
		}
		select {
		case store.passwordChecks <- struct{}{}:
			defer func() { <-store.passwordChecks }()
		default:
			http.Error(w, "authentication is busy", http.StatusServiceUnavailable)
			return
		}
		var result AuthResult
		if bootstrap {
			result, err = store.Bootstrap(r.Context(), input.Email, input.Password, input.DisplayName, input.OrganizationName)
		} else {
			result, err = store.Login(r.Context(), input.Email, input.Password)
		}
		switch {
		case errors.Is(err, ErrInvalidAccount):
			http.Error(w, err.Error(), http.StatusBadRequest)
		case errors.Is(err, ErrInvalidLogin):
			http.Error(w, err.Error(), http.StatusUnauthorized)
		case errors.Is(err, ErrNoMembership):
			http.Error(w, err.Error(), http.StatusForbidden)
		case errors.Is(err, ErrAlreadyInitialized):
			http.Error(w, err.Error(), http.StatusConflict)
		case err != nil:
			http.Error(w, "authentication failed", http.StatusInternalServerError)
		default:
			writeWorkspaceResponse(w, result, nil)
		}
	}
	route("GET /v1/auth/bootstrap-status", func(w http.ResponseWriter, r *http.Request) {
		initialized, err := store.Initialized(r.Context())
		if err != nil {
			http.Error(w, "could not read bootstrap status", http.StatusInternalServerError)
			return
		}
		writeWorkspaceResponse(w, map[string]bool{
			"available": bootstrapToken != "" && !initialized, "tokenRequired": true, "tokenAutoGenerated": false,
		}, nil)
	})
	route("POST /v1/auth/bootstrap", func(w http.ResponseWriter, r *http.Request) {
		supplied := r.Header.Get("X-ProtoVoy-Bootstrap-Token")
		if strings.TrimSpace(supplied) == "" {
			http.Error(w, "bootstrap token required", http.StatusBadRequest)
			return
		}
		hash := sha256.Sum256([]byte(supplied))
		if bootstrapToken == "" || subtle.ConstantTimeCompare(hash[:], bootstrapHash[:]) != 1 {
			http.Error(w, "invalid bootstrap token", http.StatusForbidden)
			return
		}
		authenticate(w, r, true)
	})
	route("POST /v1/auth/login", func(w http.ResponseWriter, r *http.Request) {
		authenticate(w, r, false)
	})
	route("POST /v1/auth/logout", func(w http.ResponseWriter, r *http.Request) {
		token, ok := teamBearerToken(r)
		if !ok {
			http.Error(w, "Unauthorized", http.StatusUnauthorized)
			return
		}
		if err := store.RevokeSession(r.Context(), token); err != nil {
			http.Error(w, "could not revoke session", http.StatusInternalServerError)
			return
		}
		w.WriteHeader(http.StatusNoContent)
	})
}
