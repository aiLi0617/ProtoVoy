import { expect, test } from "@playwright/test";

test.beforeEach(async ({ page }) => {
  await page.route("http://127.0.0.1:39217/**", route => route.abort());
});

test("shows auto-generated first-owner guidance while bootstrap is available", async ({ page }) => {
  await page.route("http://localhost:8088/v1/auth/bootstrap-status", route => route.fulfill({
    contentType: "application/json",
    body: JSON.stringify({ available: true, tokenRequired: true, tokenAutoGenerated: true }),
  }));
  await page.goto("/");
  await page.evaluate(() => window.dispatchEvent(new CustomEvent("protovoy-open-collaboration", { detail: "team" })));
  await page.getByRole("button", { name: "首次引导" }).click();
  await expect(page.getByText("令牌已在协作服务启动日志中生成并显示")).toBeVisible();
  await expect(page.getByLabel("引导令牌")).toBeVisible();
  await page.screenshot({ path: "output/playwright/collaboration-bootstrap.png", fullPage: true });
});

test("hides first-owner setup after bootstrap closes", async ({ page }) => {
  await page.route("http://localhost:8088/v1/auth/bootstrap-status", route => route.fulfill({
    contentType: "application/json",
    body: JSON.stringify({ available: false, tokenRequired: true, tokenAutoGenerated: true }),
  }));
  await page.goto("/");
  await page.evaluate(() => window.dispatchEvent(new CustomEvent("protovoy-open-collaboration", { detail: "team" })));
  await expect(page.getByRole("button", { name: "登录", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "首次引导" })).toHaveCount(0);
});
